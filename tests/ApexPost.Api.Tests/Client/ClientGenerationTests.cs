using System.Reflection;
using System.Text.Json;
using System.Text.RegularExpressions;
using ApexPost.Client;
using Microsoft.Extensions.DependencyInjection;

namespace ApexPost.Api.Tests.Client;

/// <summary>
/// C6: how the client is made and registered. It is generated from the committed contract with the committed NSwag
/// configuration and the pinned NSwag version; it has a method for every operation of the contract; and it is
/// registered with AddHttpClient. None of this needs the API.
/// </summary>
public sealed partial class ClientGenerationTests
{
    private static readonly string Root = FindRepositoryRoot();

    [Fact]
    public void The_committed_configuration_generates_from_the_v2_contract_into_the_generated_folder()
    {
        using var config = JsonDocument.Parse(File.ReadAllText(Path.Combine(Root, "src", "ApexPost.Client", "nswag.json")));
        var client = config.RootElement.GetProperty("codeGenerators").GetProperty("openApiToCSharpClient");

        Assert.Equal("../../contracts/v2.json", config.RootElement.GetProperty("documentGenerator").GetProperty("fromDocument").GetProperty("url").GetString());
        Assert.Equal("Generated/ApexPostClient.g.cs", client.GetProperty("output").GetString());
        Assert.True(File.Exists(Path.Combine(Root, "contracts", "v2.json")));
        Assert.True(File.Exists(Path.Combine(Root, "src", "ApexPost.Client", "Generated", "ApexPostClient.g.cs")));
    }

    [Fact]
    public void The_generated_code_says_it_comes_from_the_pinned_nswag_version()
    {
        using var tools = JsonDocument.Parse(File.ReadAllText(Path.Combine(Root, "dotnet-tools.json")));
        var pinned = tools.RootElement.GetProperty("tools").GetProperty("nswag.consolecore").GetProperty("version").GetString();
        var header = string.Join('\n', File.ReadLines(Path.Combine(Root, "src", "ApexPost.Client", "Generated", "ApexPostClient.g.cs")).Take(5));

        Assert.Contains("<auto-generated>", header);
        Assert.Equal($"{pinned}.0", ToolchainVersion().Match(header).Groups["version"].Value);
    }

    [Fact]
    public void The_client_has_a_method_for_every_operation_of_the_v2_contract_and_no_other_generated_one()
    {
        using var contract = JsonDocument.Parse(File.ReadAllText(Path.Combine(Root, "contracts", "v2.json")));
        var operationIds = contract.RootElement.GetProperty("paths").EnumerateObject()
            .SelectMany(path => path.Value.EnumerateObject().Select(operation => operation.Value.GetProperty("operationId").GetString() + "Async"));
        // Our hand-written addition in ApexPostClient.Partial.cs, not a contract operation.
        var methods = typeof(IApexPostClient).GetMethods().Select(method => method.Name).Where(name => name != nameof(IApexPostClient.TryGetShipmentAsync));

        Assert.Equal(operationIds.Order(StringComparer.Ordinal), methods.Distinct().Order(StringComparer.Ordinal));
    }

    [Theory]
    [InlineData("http://localhost:5245/")]
    [InlineData("http://localhost:5245")]
    public void Add_apex_post_client_registers_a_typed_http_client_for_the_base_address(string baseAddress)
    {
        var services = new ServiceCollection();
        services.AddApexPostClient(new Uri(baseAddress));
        using var provider = services.BuildServiceProvider();

        var client = provider.GetRequiredService<IApexPostClient>();
        var http = provider.GetRequiredService<IHttpClientFactory>().CreateClient(nameof(IApexPostClient));

        Assert.IsType<ApexPostClient>(client);
        // With the trailing slash the generated relative URLs (api/v2/...) resolve below it.
        Assert.Equal(new Uri("http://localhost:5245/"), http.BaseAddress);
        Assert.False(typeof(ApexPostClient).GetConstructors().Single().GetParameters().Any(parameter => parameter.ParameterType == typeof(string)),
            "The client takes its base address from the HttpClient, never from a constructor argument.");
    }

    private static string FindRepositoryRoot()
    {
        for (var directory = new DirectoryInfo(AppContext.BaseDirectory); directory is not null; directory = directory.Parent)
        {
            if (File.Exists(Path.Combine(directory.FullName, "ApexPost.slnx"))) return directory.FullName;
        }
        throw new InvalidOperationException("ApexPost.slnx was not found above " + AppContext.BaseDirectory);
    }

    [GeneratedRegex(@"NSwag toolchain v(?<version>[0-9.]+)")]
    private static partial Regex ToolchainVersion();
}
